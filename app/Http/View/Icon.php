    /**
     * Inline SVG for $name. $label makes the icon readable by screen readers
     * (use it only when no text sits next to the icon).
     */
    public static function svg(string $name, int $size = 16, string $class = '', ?string $label = null): string
    {
        $body = self::PATHS[$name] ?? self::PATHS['help'];
        $cls  = trim('icon icon-' . $name . ' ' . $class);
        $a11y = $label === null
            ? ' aria-hidden="true" focusable="false"'
            : ' role="img" aria-label="' . htmlspecialchars($label, ENT_QUOTES, 'UTF-8') . '"';

        return '<svg xmlns="http://www.w3.org/2000/svg" class="' . htmlspecialchars($cls, ENT_QUOTES, 'UTF-8') . '"'
            . ' width="' . $size . '" height="' . $size . '" viewBox="0 0 24 24" fill="none" stroke="currentColor"'
            . ' stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'
            // Baseline alignment for pages without app.css (print views).
            . ' style="vertical-align:-0.15em;flex-shrink:0"' . $a11y . '>' . $body . '</svg>';
    }

    /**
     * Icons for page scripts (toasts, confirm boxes): name => markup.
     *
     * @param list<string> $names
     * @return array<string, string>
     */
    public static function map(array $names, int $size = 16): array
    {
        $out = [];
        foreach ($names as $name) {
            $out[$name] = self::svg($name, $size);
        }

        return $out;
    }
